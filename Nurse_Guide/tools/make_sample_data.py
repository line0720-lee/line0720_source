def _add_text(doc, text, bold=False, size=None):
    """일반 문단을 추가한다 (제목/장/조도 일반 문단으로 넣어 파서 테스트를 단순화)."""
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.bold = bold
    if size:
        run.font.size = Pt(size)
    return para


def make_docx(path):
    """가상 투약관리지침 DOCX를 생성한다."""
    doc = Document()
    _set_korean_font(doc)

    # 머리말: 제목, 개정일, 안내문
    _add_text(doc, "가상 투약관리지침 (연습용)", bold=True, size=16)
    _add_text(doc, REVISION)
    _add_text(doc, NOTICE)

    for kind, value in DOCX_CONTENT:
        if kind == "chapter":
            _add_text(doc, value, bold=True, size=13)
        elif kind == "article":
            _add_text(doc, value, bold=True)
        elif kind == "p":
            _add_text(doc, value)
        elif kind == "table":
            table = doc.add_table(rows=0, cols=len(value[0]))
            table.style = "Table Grid"
            for r_idx, row in enumerate(value):
                cells = table.add_row().cells
                for c_idx, text in enumerate(row):
                    cells[c_idx].text = text
                    if r_idx == 0:  # 머리행은 굵게
                        for run in cells[c_idx].paragraphs[0].runs:
                            run.bold = True

    doc.save(str(path))


