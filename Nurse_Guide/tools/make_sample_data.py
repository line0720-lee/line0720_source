def _wrap(font, text, size, first_w, next_w):
    """측정한 글자 폭을 기준으로 한 줄이 여백을 넘지 않도록 줄바꿈한다."""
    lines, cur = [], ""
    width = first_w
    for ch in text:
        trial = cur + ch
        if font.text_length(trial, fontsize=size) > width and cur:
            # 공백에서 끊을 수 있으면 공백 기준으로 끊는다 (단어 중간 끊김 최소화)
            cut = cur.rfind(" ")
            if cut > len(cur) * 0.6:
                lines.append(cur[:cut])
                cur = cur[cut + 1:] + ch
            else:
                lines.append(cur)
                cur = ch
            width = next_w
        else:
            cur = trial
    if cur:
        lines.append(cur)
    return [ln.strip() for ln in lines if ln.strip()]


def _build_lines(font):
    """문서 내용을 실제로 그릴 줄 목록으로 변환한다.

    각 줄: dict(text, size, x, gap, keep, article)
      - gap: 이 줄 앞의 추가 여백
      - keep: 이 줄과 같은 쪽에 함께 있어야 하는 뒤따르는 줄 수 (제목 고립 방지)
      - article: 이 줄이 속한 조 제목 (없으면 None)
    """
    out = []

    def add(kind, text, article):
        size, ind1, ind2, gap = STYLE[kind]
        wrapped = _wrap(font, text, size, TEXT_W - ind1, TEXT_W - ind2)
        for i, ln in enumerate(wrapped):
            out.append({
                "text": ln,
                "size": size,
                "x": MARGIN_X + (ind1 if i == 0 else ind2),
                "gap": gap if i == 0 else 0,
                "keep": 0,
                "article": article,
                "kind": kind,
            })

    add("title", "가상 감염관리규정 (연습용)", None)
    add("meta", REVISION, None)
    add("meta", NOTICE, None)

    current = None
    for kind, text in PDF_CONTENT:
        if kind == "chapter":
            current = None
            add(kind, text, None)
            out[-1]["keep"] = 3      # 장 제목 + 조 제목 + 본문 2줄은 같은 쪽에
        elif kind == "article":
            current = text
            add(kind, text, current)
            out[-1]["keep"] = 2      # 조 제목 뒤 최소 2줄은 같은 쪽에
        else:
            add(kind, text, current)
    return out


def make_pdf(path):
    """가상 감염관리규정 PDF를 생성하고, 조문별 쪽 범위를 반환한다."""
    font = fitz.Font(fontfile=FONT_FILE)
    lines = _build_lines(font)

    doc = fitz.open()
    pages = []

    def new_page():
        page = doc.new_page(width=PAGE_W, height=PAGE_H)
        page.insert_font(fontname=FONT_NAME, fontfile=FONT_FILE)
        pages.append(page)
        return page

    page = new_page()
    y = TOP_Y
    article_pages = {}  # 조 제목 -> [시작 쪽, 끝 쪽] (1부터)

    for i, ln in enumerate(lines):
        step = ln["size"] * LINE_GAP
        # 이 줄과 함께 있어야 하는 줄까지의 높이를 계산하여 넘치면 다음 쪽으로
        need = ln["gap"]
        for j in range(i, min(i + ln["keep"] + 1, len(lines))):
            need += lines[j]["size"] * LINE_GAP + (lines[j]["gap"] if j > i else 0)
        if y + need - step > BOTTOM_Y and y > TOP_Y:
            page = new_page()
            y = TOP_Y
        elif y > TOP_Y:
            y += ln["gap"]

        page.insert_text((ln["x"], y), ln["text"], fontname=FONT_NAME, fontsize=ln["size"])

        art = ln["article"]
        if art:
            pno = len(pages)
            span = article_pages.setdefault(art, [pno, pno])
            span[1] = pno
        y += step

    # 모든 쪽 하단 가운데에 "- N -" 쪽번호
    # (주의: 앞서 만든 page 객체는 새 쪽 생성 후 무효가 될 수 있어 doc에서 다시 가져온다)
    for idx, pg in enumerate(doc, start=1):
        pg.insert_font(fontname=FONT_NAME, fontfile=FONT_FILE)
        label = f"- {idx} -"
        w = font.text_length(label, fontsize=10)
        pg.insert_text(((PAGE_W - w) / 2, FOOTER_Y), label, fontname=FONT_NAME, fontsize=10)

    # 맑은 고딕 전체(수 MB)가 쪽마다 들어가지 않도록 사용한 글자만 남긴다
    doc.subset_fonts()
    doc.save(str(path), garbage=4, deflate=True)
    doc.close()
    return article_pages


